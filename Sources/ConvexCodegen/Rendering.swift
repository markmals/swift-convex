    private mutating func renderDecodeDispatch(_ union: Union, name: String) {
        if union.branches.count == 1, let branch = union.branches.first {
            renderMatch(branch, union: union, name: name)
            return
        }
        emit("switch try Convex.ConvexCodec.wireKind(from: decoder) {")
        var rendered: Set<Int> = []
        for (index, branch) in union.branches.enumerated() where !rendered.contains(index) {
            // Wire kinds that select the same payload case share one `case` clause.
            var kinds = [branch.kind]
            if case .single = branch.match {
                for (otherIndex, other) in union.branches.enumerated()
                where otherIndex > index && other.match == branch.match {
                    kinds.append(other.kind)
                    rendered.insert(otherIndex)
                }
            }
            emit("case \(kinds.map { ".\($0.caseName)" }.joined(separator: ", ")):")
            indented { $0.renderMatch(branch, union: union, name: name) }
        }
        let expected = union.branches.map(\.kind.caseName).joined(separator: ", ")
        emit("default:")
        indented {
            $0.emit(
                "throw Swift.DecodingError.typeMismatch(Self.self, Swift.DecodingError.Context(codingPath: "
                    + "decoder.codingPath, debugDescription: \(Self.literal("Expected one of \(expected) for \(name)."))))"
            )
        }
        emit("}")
    }

    private mutating func renderMatch(_ branch: KindBranch, union: Union, name: String) {
        switch branch.match {
        case .single(let caseName):
            emit("return \(Self.caseExpression(caseName, union: union))")
        case .values(let branches):
            guard let scalar = branch.kind.scalarType else { return }
            emit("switch try \(scalar.source).decodeConvex(from: decoder) {")
            renderBranches(branches, union: union, wrapped: false)
            if !Self.coversBooleans(branches) {
                emit("default:")
                indented { $0.emit("throw \(Self.unknownValueError(name))") }
            }
            emit("}")
        case .discriminant(let field, let branches):
            let kinds = Set(branches.flatMap(\.values).map(\.wireKind))
            var tagType = SwiftType.convexValue
            if kinds.count == 1, let kind = kinds.first, let scalar = kind.scalarType {
                tagType = scalar
            }
            emit("let container = try decoder.container(keyedBy: DiscriminantKey.self)")
            emit("switch try container.decodeConvex(\(tagType.source).self, forKey: .tag) {")
            renderBranches(branches, union: union, wrapped: tagType == .convexValue)
            if tagType == .convexValue || !Self.coversBooleans(branches) {
                emit("default:")
                indented {
                    $0.emit(
                        "throw Swift.DecodingError.dataCorruptedError(forKey: .tag, in: container, "
                            + "debugDescription: \(Self.literal("Unknown \(field) value for \(name).")))"
                    )
                }
            }
            emit("}")
        }
    }

    private mutating func renderBranches(_ branches: [Branch], union: Union, wrapped: Bool) {
        for branch in branches where !branch.values.isEmpty {
            let patterns = branch.values.map { wrapped ? Self.valuePattern($0) : Self.pattern($0) }
            emit("case \(patterns.joined(separator: ", ")):")
            indented {
                if branch.decodesPayload {
                    $0.emit("return \(Self.caseExpression(branch.caseName, union: union))")
                } else {
                    $0.emit("return .\(Identifier.escaped(branch.caseName))")
                }
            }
        }
    }

    private static func caseExpression(_ caseName: String, union: Union) -> String {
        let payload = union.cases.first { $0.name == caseName }?.payload ?? .convexValue
        return
            ".\(Identifier.escaped(caseName))(try \(Self.receiver(payload)).decodeConvex(from: decoder))"
    }

    private static func coversBooleans(_ branches: [Branch]) -> Bool {
        let values = Set(branches.flatMap(\.values))
        return values.contains(.boolean(true)) && values.contains(.boolean(false))
    }

    private static func unknownValueError(_ name: String) -> String {
        "Swift.DecodingError.dataCorrupted(Swift.DecodingError.Context(codingPath: decoder.codingPath, "
            + "debugDescription: \(literal("Unknown value for \(name)."))))"
    }

    // MARK: Source text

    /// A type spelled so a static member can follow it.
    private static func receiver(_ type: SwiftType) -> String {
        switch type {
        case .array(let element): "Swift.Array<\(element.source)>"
        case .dictionary(let key, let value): "Swift.Dictionary<\(key.source), \(value.source)>"
        case .optional(let wrapped): "Swift.Optional<\(wrapped.source)>"
        default: type.source
        }
    }

    private static func pattern(_ value: LiteralValue) -> String {
        switch value {
        case .string(let text): literal(text)
        case .boolean(let flag): flag ? "true" : "false"
        case .float64(let number): number.description
        case .int64(let number): String(number)
        }
    }

    private static func valuePattern(_ value: LiteralValue) -> String {
        switch value {
        case .string(let text): ".string(\(literal(text)))"
        case .boolean(let flag): ".boolean(\(flag))"
        case .float64(let number): ".float64(\(number.description))"
        case .int64(let number): ".int64(\(number))"
        }
    }

    private static func typedLiteral(_ value: LiteralValue) -> String {
        switch value {
        case .string(let text): "(\(literal(text)) as Swift.String)"
        case .boolean(let flag): "(\(flag) as Swift.Bool)"
        case .float64(let number): "(\(number.description) as Swift.Double)"
        case .int64(let number): "(\(number) as Swift.Int64)"
        }
    }

    /// A Swift string literal with every non-printable or non-ASCII scalar escaped.
    static func literal(_ text: String) -> String {
        var result = "\""
        for scalar in text.unicodeScalars {
            switch scalar {
            case "\\": result += "\\\\"
            case "\"": result += "\\\""
            case "\n": result += "\\n"
            case "\r": result += "\\r"
            case "\t": result += "\\t"
            case "\0": result += "\\0"
            default:
                if scalar.isASCII, scalar.value >= 0x20, scalar.value != 0x7F {
                    result.unicodeScalars.append(scalar)
                } else {
                    result += "\\u{\(String(scalar.value, radix: 16, uppercase: true))}"
                }
            }
        }
        return result + "\""
    }

    private static func comment(_ text: String) -> String {
        String(
            String.UnicodeScalarView(
                text.unicodeScalars.map { $0.value < 0x20 || $0.value == 0x7F ? " " : $0 }
            )
        )
    }

    private mutating func documentation(_ text: [String]) {
        for line in text {
            let cleaned = Self.comment(line)
            emit(cleaned.isEmpty ? "///" : "/// \(cleaned)")
        }
    }

    private mutating func emit(_ line: String) {
        lines.append(line.isEmpty ? "" : String(repeating: "    ", count: depth) + line)
    }

    private mutating func indented(_ body: (inout SwiftRenderer) -> Void) {
        depth += 1
        body(&self)
        depth -= 1
    }
}

extension Union {
    /// The discriminant field of the object branch, when objects are selected by a tag.
    var discriminantField: String? {
        for branch in branches {
            if case .discriminant(let field, _) = branch.match {
                return field
            }
        }
        return nil
    }
