import ConvexContract

/// Renders lowered declarations as one deterministic Swift source file.
///
/// Every type reference is fully qualified (`Swift.String`, `API.Tables.Messages`) so generated
/// names can never shadow the types that generated code depends on.
struct SwiftRenderer {
    private var lines: [String] = []
    private var depth = 0

    static func render(_ module: GeneratedModule) -> String {
        var renderer = SwiftRenderer()
        renderer.renderFile(module)
        return renderer.lines.joined(separator: "\n") + "\n"
    }

    private mutating func renderFile(_ module: GeneratedModule) {
        let provenance = module.provenance
        emit(
            "// Generated by convex-swift-codegen. Do not edit; regenerate from the Convex contract."
        )
        emit(
            "// Contract format 1 from exporter \(Self.comment(provenance.exporterVersion)), "
                + "Convex \(Self.comment(provenance.convexVersion)), "
                + "TypeScript \(Self.comment(provenance.typescriptVersion))."
        )
        emit("// Source hash: \(Self.comment(provenance.sourceHash))")
        emit("")
        let usesConvex = module.declarations.contains { declaration in
            guard case .namespace = declaration.kind else { return true }
            return false
        }
        emit(usesConvex ? "public import Convex" : "import Convex")
        if module.declarations.contains(where: Self.usesData) {
            emit("public import Foundation")
        }
        for declaration in module.declarations {
            emit("")
            if declaration.name.components.count == 1 {
                renderDeclaration(declaration)
            } else {
                emit("extension \(declaration.name.parent) {")
                indented { $0.renderDeclaration(declaration) }
                emit("}")
            }
        }
    }

    private static func usesData(_ declaration: Declaration) -> Bool {
        switch declaration.kind {
        case .namespace, .table:
            false
        case .model(let properties):
            properties.contains { $0.type.usesData }
        case .tuple(let elements):
            elements.contains { $0.type.usesData }
        case .union(let union):
            union.cases.contains { $0.payload?.usesData == true }
        case .alias(let type):
            type.usesData
        case .request(let request):
            request.properties.contains { $0.type.usesData }
        }
    }

    // MARK: Declarations

    private mutating func renderDeclaration(_ declaration: Declaration) {
        documentation(declaration.documentation)
        let name = declaration.name.name
        switch declaration.kind {
        case .namespace:
            emit("public enum \(name) {}")
        case .table(let wireName):
            emit("public enum \(name): Convex.ConvexTable {")
            indented {
                $0.documentation(["The backend table name."])
                $0.emit("public static let name: Swift.String = \(Self.literal(wireName))")
            }
            emit("}")
        case .alias(let type):
            emit("public typealias \(name) = \(type.source)")
        case .model(let properties):
            emit("public struct \(name): Swift.Sendable, Convex.ConvexValueCodable {")
            indented { $0.renderModelBody(properties) }
            emit("}")
        case .tuple(let elements):
            emit("public struct \(name): Swift.Sendable, Convex.ConvexValueCodable {")
            indented { $0.renderTupleBody(elements) }
            emit("}")
        case .union(let union):
            renderUnion(union, name: name)
        case .request(let request):
            let conformance =
                switch request.kind {
                case .query: "Convex.QueryRequest"
                case .mutation: "Convex.MutationRequest"
                case .action: "Convex.ActionRequest"
                }
            emit("public struct \(name): \(conformance) {")
            indented { $0.renderRequestBody(request) }
            emit("}")
        }
    }

    private mutating func renderModelBody(_ properties: [Property]) {
        for property in properties {
            documentation(property.documentation)
            emit("public var \(Identifier.escaped(property.name)): \(property.type.source)")
            emit("")
        }
        renderInitializer(properties, summary: "Creates a value from its fields.")
        emit("")
        if properties.isEmpty {
            emit("private enum CodingKeys: Swift.CodingKey {}")
        } else {
            emit("private enum CodingKeys: Swift.String, Swift.CodingKey {")
            indented {
                for property in properties {
                    $0.emit(
                        "case \(Identifier.escaped(property.name)) = \(Self.literal(property.wireName))"
                    )
                }
            }
            emit("}")
        }
        emit("")
        documentation(["Encodes the fields with their exact wire keys and presence."])
        emit("public func encodeConvex(to encoder: any Swift.Encoder) throws {")
        indented {
            if properties.isEmpty {
                $0.emit("_ = encoder.container(keyedBy: CodingKeys.self)")
                return
            }
            $0.emit("var container = encoder.container(keyedBy: CodingKeys.self)")
            for property in properties {
                let method =
                    switch property.presence {
                    case .required: "encodeConvex"
                    case .optional: "encodeConvexIfPresent"
                    case .optionalNullable: "encodeConvexField"
                    }
                let name = Identifier.escaped(property.name)
                $0.emit("try container.\(method)(self.\(name), forKey: .\(name))")
            }
        }
        emit("}")
        emit("")
        documentation(["Decodes the fields, rejecting missing required keys and invalid nulls."])
        emit("public static func decodeConvex(from decoder: any Swift.Decoder) throws -> Self {")
        indented {
            if properties.isEmpty {
                $0.emit("_ = try decoder.container(keyedBy: CodingKeys.self)")
                $0.emit("return Self()")
                return
            }
            $0.emit("let container = try decoder.container(keyedBy: CodingKeys.self)")
            $0.emit("return try Self(")
            $0.indented {
                for (index, property) in properties.enumerated() {
                    let method =
                        switch property.presence {
                        case .required: "decodeConvex"
                        case .optional: "decodeConvexIfPresent"
                        case .optionalNullable: "decodeConvexField"
                        }
                    let name = Identifier.escaped(property.name)
                    let separator = index == properties.count - 1 ? "" : ","
                    $0.emit(
                        "\(property.name): container.\(method)(\(property.valueType.source).self, forKey: .\(name))\(separator)"
                    )
                }
            }
            $0.emit(")")
        }
        emit("}")
    }

    private mutating func renderInitializer(_ properties: [Property], summary: String) {
        documentation([summary])
        let parameters = properties.map { property in
            let name = Identifier.escaped(property.name)
            let defaultValue =
                switch property.presence {
                case .required: ""
                case .optional: " = nil"
                case .optionalNullable: " = .omitted"
                }
            return "\(name): \(property.type.source)\(defaultValue)"
        }
        guard !parameters.isEmpty else {
            emit("public init() {}")
            return
        }
        emit("public init(")
        indented {
            for (index, parameter) in parameters.enumerated() {
                $0.emit(parameter + (index == parameters.count - 1 ? "" : ","))
            }
        }
        emit(") {")
        indented {
            for property in properties {
                let name = Identifier.escaped(property.name)
                $0.emit("self.\(name) = \(name)")
            }
        }
        emit("}")
    }

    private mutating func renderRequestBody(_ request: Request) {
        documentation(["The exact backend function address."])
        emit("public static let functionPath: Swift.String = \(Self.literal(request.functionPath))")
        emit("")
        for property in request.properties {
            documentation(property.documentation)
            emit("public let \(Identifier.escaped(property.name)): \(property.type.source)")
            emit("")
        }
        renderInitializer(
            request.properties,
            summary: "Creates a request without performing any I/O."
        )
        emit("")
        documentation(["Encodes each present argument as Convex JSON under its exact wire key."])
        emit("public func encodeArguments() throws -> [Swift.String: Swift.String] {")
        indented {
            guard !request.properties.isEmpty else {
                $0.emit("[:]")
                return
            }
            $0.emit("var arguments: [Swift.String: Swift.String] = [:]")
            for property in request.properties {
                let name = Identifier.escaped(property.name)
                let key = Self.literal(property.wireName)
                switch property.presence {
                case .required:
                    $0.emit("arguments[\(key)] = try Convex.ConvexCodec.encode(self.\(name))")
                case .optional:
                    $0.emit("if let value = self.\(name) {")
                    $0.indented {
                        $0.emit("arguments[\(key)] = try Convex.ConvexCodec.encode(value)")
                    }
                    $0.emit("}")
                case .optionalNullable:
                    $0.emit("if case .value(let value) = self.\(name) {")
                    $0.indented {
                        $0.emit("arguments[\(key)] = try Convex.ConvexCodec.encode(value)")
                    }
                    $0.emit("}")
                }
            }
            $0.emit("return arguments")
        }
        emit("}")
    }

    private mutating func renderTupleBody(_ elements: [TupleElement]) {
        for element in elements {
            documentation(element.documentation)
            emit("public var \(Identifier.escaped(element.name)): \(element.type.source)")
            emit("")
        }
        documentation(["Creates a tuple from its elements in order."])
        if elements.isEmpty {
            emit("public init() {}")
        } else {
            let parameters = elements.map { "_ \(Identifier.escaped($0.name)): \($0.type.source)" }
            emit("public init(\(parameters.joined(separator: ", "))) {")
            indented {
                for element in elements {
                    let name = Identifier.escaped(element.name)
                    $0.emit("self.\(name) = \(name)")
                }
            }
            emit("}")
        }
        emit("")
        documentation(["Encodes the elements as a fixed-length array."])
        emit("public func encodeConvex(to encoder: any Swift.Encoder) throws {")
        indented {
            if elements.isEmpty {
                $0.emit("_ = encoder.unkeyedContainer()")
                return
            }
            $0.emit("var container = encoder.unkeyedContainer()")
            for element in elements {
                $0.emit("try container.encodeConvex(self.\(Identifier.escaped(element.name)))")
            }
        }
        emit("}")
        emit("")
        documentation([
            "Decodes exactly \(elements.count) elements, rejecting arrays of any other length."
        ])
        emit("public static func decodeConvex(from decoder: any Swift.Decoder) throws -> Self {")
        indented {
            let lengthError =
                "Swift.DecodingError.dataCorrupted(Swift.DecodingError.Context(codingPath: decoder.codingPath, "
                + "debugDescription: \"Expected exactly \(elements.count) tuple elements.\"))"
            if elements.isEmpty {
                $0.emit("let container = try decoder.unkeyedContainer()")
                $0.emit("guard container.isAtEnd else {")
                $0.indented { $0.emit("throw \(lengthError)") }
                $0.emit("}")
                $0.emit("return Self()")
                return
            }
            $0.emit("var container = try decoder.unkeyedContainer()")
            $0.emit("if let count = container.count, count != \(elements.count) {")
            $0.indented { $0.emit("throw \(lengthError)") }
            $0.emit("}")
            for element in elements {
                $0.emit(
                    "let \(Identifier.escaped(element.name)) = try container.decodeConvex(\(element.type.source).self)"
                )
            }
            $0.emit("guard container.isAtEnd else {")
            $0.indented { $0.emit("throw \(lengthError)") }
            $0.emit("}")
            let arguments = elements.map { Identifier.escaped($0.name) }.joined(separator: ", ")
            $0.emit("return Self(\(arguments))")
        }
        emit("}")
    }

    // MARK: Unions

    private mutating func renderUnion(_ union: Union, name: String) {
        if union.isStringLiteralOnly {
            renderStringEnum(union, name: name)
            return
        }
        let conformances =
            union.isLiteralOnly
            ? "Swift.Hashable, Swift.Sendable, Swift.CaseIterable, Convex.ConvexValueCodable"
            : "Swift.Sendable, Convex.ConvexValueCodable"
        emit("public enum \(name): \(conformances) {")
        indented { renderer in
            for unionCase in union.cases {
                renderer.documentation(unionCase.documentation)
                if let payload = unionCase.payload {
                    renderer.emit("case \(Identifier.escaped(unionCase.name))(\(payload.source))")
                } else {
                    renderer.emit("case \(Identifier.escaped(unionCase.name))")
                }
            }
            renderer.emit("")
            if let field = union.discriminantField {
                renderer.emit("private enum DiscriminantKey: Swift.String, Swift.CodingKey {")
                renderer.indented { $0.emit("case tag = \(Self.literal(field))") }
                renderer.emit("}")
                renderer.emit("")
            }
            renderer.documentation(["Encodes the selected case with its own wire representation."])
            renderer.emit("public func encodeConvex(to encoder: any Swift.Encoder) throws {")
            renderer.indented { renderer in
                renderer.emit("switch self {")
                for unionCase in union.cases {
                    let caseName = Identifier.escaped(unionCase.name)
                    if unionCase.payload != nil {
                        renderer.emit("case .\(caseName)(let value):")
                        renderer.indented { $0.emit("try value.encodeConvex(to: encoder)") }
                    } else if let literal = unionCase.literal {
                        renderer.emit("case .\(caseName):")
                        renderer.indented {
                            $0.emit("try \(Self.typedLiteral(literal)).encodeConvex(to: encoder)")
                        }
                    }
                }
                renderer.emit("}")
            }
            renderer.emit("}")
            renderer.emit("")
            renderer.documentation([
                "Decodes the case selected by the value's wire kind, literal value, or discriminant field.",
                "",
                "Values that match no case are rejected; decoding never tries cases in order.",
            ])
            renderer.emit(
                "public static func decodeConvex(from decoder: any Swift.Decoder) throws -> Self {"
            )
            renderer.indented { $0.renderDecodeDispatch(union, name: name) }
            renderer.emit("}")
        }
        emit("}")
    }

