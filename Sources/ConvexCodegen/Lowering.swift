public import ConvexContract

extension ContractDiagnostic.Code {
    /// Union variants overlap on the wire, so decoding would have to guess a case.
    public static let overlappingUnion = Self(rawValue: "overlappingUnion")
    /// Two generated Swift names collide, or a name is reserved in generated code.
    public static let nameCollision = Self(rawValue: "nameCollision")
    /// No Swift identifier can be derived from a backend name.
    public static let unnameable = Self(rawValue: "unnameable")
    /// A configured namespace or name override is not a usable Swift identifier.
    public static let invalidName = Self(rawValue: "invalidName")
    /// A `names` override matches no generated declaration.
    public static let unusedNameOverride = Self(rawValue: "unusedNameOverride")
}

/// Translates a validated contract into Swift declarations, collecting every naming and union problem.
struct Lowerer {
    /// How a generated nested type gets its name.
    private enum Naming {
        /// The position's own path is a `names` key that can rename the type.
        case position(ContractPath)
        /// The name derives from a property or case, which `names` renames through this path.
        case derived(ContractPath)
    }

    /// A union after flattening, deduplication, and null extraction.
    private enum Normalized {
        case invalid
        case null
        case single(Shape, ContractPath)
        case nullable(Shape, ContractPath)
        case literals([(LiteralValue, ContractPath)], nullable: Bool)
        case union([(Shape, ContractPath)], nullable: Bool)
    }

    /// The values a shape accepts for one wire kind.
    private enum Constraint {
        case any
        case values(Set<LiteralValue>)
        case object(ObjectShape)
    }

    private struct Lowered {
        var type: SwiftType
        var nullable: Bool
    }

    private struct Member {
        var label: String
        var key: ContractPath?
    }

    private struct Scope {
        var reserved: Set<String> = []
        var members: [String: Member] = [:]
        var lowercasedTypes: [String: Member] = [:]
    }

    private struct UnionPlan {
        var groups: [(kind: WireKind, indices: [Int])]
        var discriminant: String?
        var tags: [Int: [LiteralValue]]
    }

    private static let reservedModules: Set = ["Convex", "Foundation", "Swift"]

    private let contract: ContractDocument
    private let root: QualifiedName
    private var overrides: NameOverrides
    private var diagnostics: [ContractDiagnostic] = []
    private var declarations: [Declaration] = []
    private var scopes: [QualifiedName: Scope] = [:]
    private var namedTypes: [String: QualifiedName] = [:]
    private var tableTypes: [String: QualifiedName] = [:]
    private var moduleNamespaces: [String: QualifiedName] = [:]
    private var source: SourceLocation?

    init(contract: ContractDocument, namespace: String, overrides: NameOverrides) {
        self.contract = contract
        self.root = QualifiedName([namespace])
        self.overrides = overrides
    }

    /// Lowers the whole contract, or returns the diagnostics that prevent generation.
    mutating func lower() -> Result<GeneratedModule, ContractError> {
        validateConfiguration()
        if diagnostics.isEmpty {
            scopes[root] = Scope()
            declarations.append(
                Declaration(
                    name: root,
                    documentation: [
                        "Requests, tables, and types generated from a Convex contract.",
                        "",
                        "Generated by `convex-swift-codegen`; regenerate instead of editing.",
                    ],
                    kind: .namespace
                )
            )
            declareTables()
            declareNamedTypes()
            lowerFunctions()
            lowerTableDocuments()
            lowerNamedTypeBodies()
        }
        if diagnostics.isEmpty {
            for key in overrides.unusedKeys {
                diagnostics.append(
                    ContractDiagnostic(
                        code: .unusedNameOverride,
                        message: "The `names` override `\(key)` matches no generated declaration.",
                        file: .configuration,
                        location: overrides.location(of: key)
                    )
                )
            }
        }
        guard diagnostics.isEmpty else {
            return .failure(ContractError(diagnostics: diagnostics.sortedForReport()))
        }
        return .success(
            GeneratedModule(
                provenance: contract.provenance,
                declarations: declarations.sorted { $0.name < $1.name }
            )
        )
    }

    // MARK: Top-level declarations

    private mutating func validateConfiguration() {
        let namespace = root.name
        if !Identifier.isValid(namespace) || Identifier.keywords.contains(namespace)
            || Self.reservedModules.contains(namespace)
        {
            diagnostics.append(
                ContractDiagnostic(
                    code: .invalidName,
                    message: "The namespace `\(namespace)` is not a usable Swift type name.",
                    file: .configuration
                )
            )
        }
        for (key, value) in overrides.entries where !Identifier.isValid(value) {
            diagnostics.append(
                ContractDiagnostic(
                    code: .invalidName,
                    message:
                        "The `names` override for `\(key)` is `\(value)`, which is not an ASCII Swift identifier.",
                    file: .configuration,
                    location: overrides.location(of: key)
                )
            )
        }
    }

    private mutating func declareTables() {
        var names = Set(contract.tables.map(\.name))
        if referencesStorage() {
            names.insert("_storage")
        }
        guard !names.isEmpty else {
            return
        }
        let namespace = root.child("Tables")
        register(
            "Tables",
            in: root,
            isType: true,
            label: "the generated `Tables` namespace",
            key: nil,
            origin: nil
        )
        scopes[namespace] = Scope()
        declarations.append(
            Declaration(
                name: namespace,
                documentation: ["Table identities and document types."],
                kind: .namespace
            )
        )
        for name in names.sorted() {
            let path = ContractPath.table(name)
            let swiftName = resolveName(
                for: path,
                derived: Identifier.upperCamel(name),
                what: "table"
            )
            register(
                swiftName,
                in: namespace,
                isType: true,
                label: "`\(path)`",
                key: path,
                origin: path
            )
            let type = namespace.child(swiftName)
            tableTypes[name] = type
            scopes[type] = Scope(reserved: ["name"])
            declarations.append(
                Declaration(
                    name: type,
                    documentation: ["The `\(name)` table, used to brand its document IDs."],
                    kind: .table(wireName: name)
                )
            )
        }
    }

    private mutating func declareNamedTypes() {
        guard !contract.types.isEmpty else {
            return
        }
        let namespace = root.child("Types")
        register(
            "Types",
            in: root,
            isType: true,
            label: "the generated `Types` namespace",
            key: nil,
            origin: nil
        )
        scopes[namespace] = Scope()
        declarations.append(
            Declaration(
                name: namespace,
                documentation: ["Named types shared by functions and tables."],
                kind: .namespace
            )
        )
        for key in contract.types.keys.sorted() {
            let path = ContractPath.type(key)
            let name = resolveName(
                for: path,
                derived: Identifier.upperCamel(key),
                what: "named type"
            )
            register(name, in: namespace, isType: true, label: "`\(path)`", key: path, origin: path)
            namedTypes[key] = namespace.child(name)
        }
    }

    private mutating func lowerFunctions() {
        for function in contract.functions {
            source = function.source
            let path = ContractPath.function(function.path)
            var parent = root
            for index in function.module.indices {
                let modulePath = function.module[...index].joined(separator: "/")
                if let existing = moduleNamespaces[modulePath] {
                    parent = existing
                    continue
                }
                let key = ContractPath.module(modulePath)
                let name = resolveName(
                    for: key,
                    derived: Identifier.upperCamel(function.module[index]),
                    what: "module"
                )
                register(name, in: parent, isType: true, label: "`\(key)`", key: key, origin: path)
                let namespace = parent.child(name)
                moduleNamespaces[modulePath] = namespace
                scopes[namespace] = Scope()
                declarations.append(
                    Declaration(
                        name: namespace,
                        documentation: ["Functions in the `\(modulePath)` module."],
                        kind: .namespace
                    )
                )
                parent = namespace
            }
            let name = resolveName(
                for: path,
                derived: Identifier.upperCamel(function.name),
                what: "function"
            )
            register(name, in: parent, isType: true, label: "`\(path)`", key: path, origin: path)
            lowerRequest(function, at: path, type: parent.child(name))
        }
        source = nil
    }

    private mutating func lowerRequest(
        _ function: ContractFunction,
        at path: ContractPath,
        type: QualifiedName
    ) {
        scopes[type] = Scope(reserved: ["encodeArguments", "functionPath"])
        let resultPath = path.member("result")
        register(
            "Output",
            in: type,
            isType: true,
            label: "the result type `Output`",
            key: nil,
            origin: resultPath
        )
        let properties = lowerProperties(
            function.arguments,
            objectPath: path.member("arguments"),
            owner: type,
            role: "argument"
        )
        lowerNominal(
            function.result,
            at: resultPath,
            type: type.child("Output"),
            documentation: ["The decoded result of `\(function.path)`."]
        )
        var documentation = ["Calls the `\(function.path)` \(function.kind.rawValue)."]
        documentation.append("")
        documentation.append(
            "Constructing a request performs no I/O. Pass it to the `ConvexClient` method for its kind."
        )
        if let source = function.source {
            documentation.append("")
            documentation.append("Defined in `\(source)`.")
        }
        documentation.append("")
        switch function.typeSource {
        case .inferred:
            documentation.append("Types are inferred from the backend's TypeScript source.")
        case .validator:
            documentation.append("Types derive from the backend's Convex validators.")
        case .dynamic:
            documentation.append(
                "The contract opts some positions into dynamic values; those decode as `ConvexValue`."
            )
        }
        declarations.append(
            Declaration(
                name: type,
                documentation: documentation,
                kind: .request(
                    Request(
                        kind: function.kind,
                        functionPath: function.path,
                        properties: properties
                    )
                )
            )
        )
    }

    private mutating func lowerTableDocuments() {
        for table in contract.tables {
            guard let type = tableTypes[table.name] else {
                continue
            }
            let path = ContractPath.table(table.name).member("document")
            register(
                "Document",
                in: type,
                isType: true,
                label: "the document type",
                key: nil,
                origin: path
            )
            lowerNominal(
                table.document,
                at: path,
                type: type.child("Document"),
                documentation: ["A document in the `\(table.name)` table."]
            )
        }
    }

    private mutating func lowerNamedTypeBodies() {
        for key in contract.types.keys.sorted() {
            guard let type = namedTypes[key], let shape = contract.types[key] else {
                continue
            }
            lowerNominal(
                shape,
                at: .type(key),
                type: type,
                documentation: ["The contract's `\(key)` type."]
            )
        }
    }

    // MARK: Shapes

    /// Lowers a shape whose Swift type must be addressable by an already registered `type` name.
    ///
    /// A shape that needs its own declaration takes the name directly; anything else becomes a type
    /// alias, and a nullable declaration is named with a `Value` suffix.
    private mutating func lowerNominal(
        _ shape: Shape,
        at path: ContractPath,
        type: QualifiedName,
        documentation: [String]
    ) {
        switch normalize(shape, at: path) {
        case .invalid:
            return
        case .single(.object(let object), let objectPath):
            emitModel(object, at: objectPath, type: type, documentation: documentation)
        case .single(.tuple(let elements), let tuplePath):
            emitTuple(elements, at: tuplePath, type: type, documentation: documentation)
        case .single(.literal(let value), let literalPath):
            emitUnion(
                [(.literal(value), literalPath.member("value"))],
                at: literalPath,
                type: type,
                documentation: documentation
            )
        case .literals(let values, false):
            emitUnion(
                values.map { (Shape.literal($0.0), $0.1) },
                at: path,
                type: type,
                documentation: documentation
            )
        case .union(let variants, false):
            emitUnion(variants, at: path, type: type, documentation: documentation)
        case .nullable(let inner, _) where Self.needsDeclaration(inner):
            aliasNominal(
                shape,
                at: path,
                type: type,
                base: type.name + "Value",
                documentation: documentation
            )
        case .literals(_, true), .union(_, true):
            aliasNominal(
                shape,
                at: path,
                type: type,
                base: type.name + "Value",
                documentation: documentation
            )
        case .null, .single, .nullable:
            aliasNominal(shape, at: path, type: type, base: type.name, documentation: documentation)
        }
    }

    private mutating func aliasNominal(
        _ shape: Shape,
        at path: ContractPath,
        type: QualifiedName,
        base: String,
        documentation: [String]
    ) {
        // The base already reflects any override of `type`, so nested names derive from it.
        let lowered = lowerShape(
            shape,
            at: path,
            parent: type.parent,
            base: base,
            naming: .derived(path)
        )
        declarations.append(
            Declaration(name: type, documentation: documentation, kind: .alias(lowered.type))
        )
    }

    private static func needsDeclaration(_ shape: Shape) -> Bool {
        switch shape {
        case .object, .tuple, .literal: true
        default: false
        }
    }

    private mutating func lowerShape(
        _ shape: Shape,
        at path: ContractPath,
        parent: QualifiedName,
        base: String,
        naming: Naming
    ) -> Lowered {
        switch normalize(shape, at: path) {
        case .invalid:
            return Lowered(type: .convexValue, nullable: true)
        case .null:
            return Lowered(type: .convexNull, nullable: true)
        case .single(let single, let singlePath):
            return lowerSingle(single, at: singlePath, parent: parent, base: base, naming: naming)
        case .nullable(let inner, let innerPath):
            let lowered = lowerSingle(
                inner,
                at: innerPath,
                parent: parent,
                base: base,
                naming: naming
            )
            return Lowered(type: .optional(lowered.type), nullable: true)
        case .literals(let values, let nullable):
            let type = declareNested(in: parent, base: base, naming: naming, origin: path)
            emitUnion(
                values.map { (Shape.literal($0.0), $0.1) },
                at: path,
                type: type,
                documentation: ["One of the literal values allowed at `\(path)`."]
            )
            return Lowered(
                type: nullable ? .optional(.named(type)) : .named(type),
                nullable: nullable
            )
        case .union(let variants, let nullable):
            let type = declareNested(in: parent, base: base, naming: naming, origin: path)
            emitUnion(
                variants,
                at: path,
                type: type,
                documentation: ["One of the variants allowed at `\(path)`."]
            )
            return Lowered(
                type: nullable ? .optional(.named(type)) : .named(type),
                nullable: nullable
            )
        }
    }

    private mutating func lowerSingle(
        _ shape: Shape,
        at path: ContractPath,
        parent: QualifiedName,
        base: String,
        naming: Naming
    ) -> Lowered {
        switch shape {
        case .string:
            return Lowered(type: .string, nullable: false)
        case .boolean:
            return Lowered(type: .bool, nullable: false)
        case .float64:
            return Lowered(type: .double, nullable: false)
        case .int64:
            return Lowered(type: .int64, nullable: false)
        case .bytes:
            return Lowered(type: .data, nullable: false)
        case .null:
            return Lowered(type: .convexNull, nullable: true)
        case .dynamic:
            return Lowered(type: .convexValue, nullable: true)
        case .id(let table):
            return Lowered(type: .documentID(table: tableTypes[table] ?? root), nullable: false)
        case .array(let element):
            let elementPath = path.member("element")
            let lowered = lowerShape(
                element,
                at: elementPath,
                parent: parent,
                base: base + "Element",
                naming: .position(elementPath)
            )
            return Lowered(type: .array(lowered.type), nullable: false)
        case .record(let key, let value):
            let keyType = lowerRecordKey(
                key,
                at: path.member("key"),
                parent: parent,
                base: base + "Key"
            )
            let valuePath = path.member("value")
            let lowered = lowerShape(
                value,
                at: valuePath,
                parent: parent,
                base: base + "Value",
                naming: .position(valuePath)
            )
            return Lowered(type: .dictionary(key: keyType, value: lowered.type), nullable: false)
        case .ref(let name):
            return Lowered(type: .named(namedTypes[name] ?? root), nullable: isNullable(shape))
        case .object(let object):
            let type = declareNested(in: parent, base: base, naming: naming, origin: path)
            emitModel(object, at: path, type: type, documentation: ["The object at `\(path)`."])
            return Lowered(type: .named(type), nullable: false)
        case .tuple(let elements):
            let type = declareNested(in: parent, base: base, naming: naming, origin: path)
            emitTuple(
                elements,
                at: path,
                type: type,
                documentation: ["The fixed-length tuple at `\(path)`."]
            )
            return Lowered(type: .named(type), nullable: false)
        case .literal(let value):
            let type = declareNested(in: parent, base: base, naming: naming, origin: path)
            emitUnion(
                [(.literal(value), path.member("value"))],
                at: path,
                type: type,
                documentation: ["The single literal value allowed at `\(path)`."]
            )
            return Lowered(type: .named(type), nullable: false)
        case .union:
            // `normalize` never produces a nested union.
            return Lowered(type: .convexValue, nullable: true)
        }
    }

    private mutating func lowerRecordKey(
        _ shape: Shape,
        at path: ContractPath,
        parent: QualifiedName,
        base: String
    ) -> SwiftType {
        if case .ref(let name) = shape, let type = namedTypes[name] {
            return .named(type)
        }
        var hasString = false
        var tables: Set<String> = []
        var literals: [(LiteralValue, ContractPath)] = []
        collectKeyParts(
            shape,
            at: path,
            hasString: &hasString,
            tables: &tables,
            literals: &literals
        )
        if hasString {
            return .string
        }
        if let table = tables.first {
            if tables.count == 1, literals.isEmpty {
                return .documentID(table: tableTypes[table] ?? root)
            }
            report(
                .overlappingUnion,
                "Record key variants overlap: document IDs are strings, so they cannot share a key union with other IDs or literals.",
                path
            )
            return .string
        }
        let type = declareNested(in: parent, base: base, naming: .position(path), origin: path)
        emitUnion(
            literals.map { (Shape.literal($0.0), $0.1) },
            at: path,
            type: type,
            documentation: ["The keys allowed at `\(path)`."]
        )
        return .named(type)
    }

    private func collectKeyParts(
        _ shape: Shape,
        at path: ContractPath,
        hasString: inout Bool,
        tables: inout Set<String>,
        literals: inout [(LiteralValue, ContractPath)]
    ) {
        switch shape {
        case .string:
            hasString = true
        case .id(let table):
            tables.insert(table)
        case .literal(let value):
            if !literals.contains(where: { $0.0 == value }) {
                literals.append((value, path))
            }
        case .union(let variants):
            for (index, variant) in variants.enumerated() {
                collectKeyParts(
                    variant,
                    at: path.member("variants").index(index),
                    hasString: &hasString,
                    tables: &tables,
                    literals: &literals
                )
            }
        case .ref(let name):
            if let target = contract.types[name] {
                collectKeyParts(
                    target,
                    at: .type(name),
                    hasString: &hasString,
                    tables: &tables,
                    literals: &literals
                )
            }
        default:
            // Contract validation rejects other record key shapes.
            break
        }
    }

    // MARK: Declarations

    private mutating func emitModel(
        _ object: ObjectShape,
        at path: ContractPath,
        type: QualifiedName,
        documentation: [String]
    ) {
        scopes[type] = Scope(reserved: [
            "CodingKeys", "decodeConvex", "encodeConvex", "intValue", "stringValue",
        ])
        let properties = lowerProperties(object, objectPath: path, owner: type, role: "field")
        declarations.append(
            Declaration(name: type, documentation: documentation, kind: .model(properties))
        )
    }

    private mutating func lowerProperties(
        _ object: ObjectShape,
        objectPath: ContractPath,
        owner: QualifiedName,
        role: String
    ) -> [Property] {
        var properties: [Property] = []
        for field in object.fields.sorted(by: { $0.name < $1.name }) {
            let path = objectPath.key(field.name)
            let name: String
            let typeBase: String
            if let override = overrides.take(path) {
                name = override
                typeBase = Identifier.upperFirst(override)
            } else if let lower = Identifier.lowerCamel(field.name),
                let upper = Identifier.upperCamel(field.name)
            {
                name = lower
                typeBase = upper
            } else {
                _ = unnameable(path, role)
                continue
            }
            register(name, in: owner, isType: false, label: "`\(path)`", key: path, origin: path)
            let lowered = lowerShape(
                field.type,
                at: path,
                parent: owner,
                base: typeBase,
                naming: .derived(path)
            )
            let presence: Presence
            let type: SwiftType
            if !field.optional {
                presence = .required
                type = lowered.type
            } else if lowered.nullable {
                presence = .optionalNullable
                type = .field(lowered.type)
            } else {
                presence = .optional
                type = .optional(lowered.type)
            }
            properties.append(
                Property(
                    name: name,
                    wireName: field.name,
                    type: type,
                    valueType: lowered.type,
                    presence: presence,
                    documentation: propertyDocumentation(
                        field,
                        role: role,
                        presence: presence,
                        lowered: lowered
                    )
                )
            )
        }
        return properties
    }

    private func propertyDocumentation(
        _ field: Field,
        role: String,
        presence: Presence,
        lowered: Lowered
    ) -> [String] {
        var lines = ["The `\(field.name)` \(role)."]
        var notes: [String] = []
        switch presence {
        case .required where lowered.nullable:
            notes.append("Required; `nil` encodes an explicit `null`.")
        case .required:
            break
        case .optional:
            notes.append("Omitted when `nil`; an explicit `null` is invalid.")
        case .optionalNullable:
            notes.append(
                "`.omitted` leaves the key out, and `.value(nil)` encodes an explicit `null`."
            )
        }
        switch contract.resolved(field.type) {
        case .float64 where field.name == "_creationTime":
            notes.append("Milliseconds since the Unix epoch, as a Convex Float64.")
        case .float64:
            notes.append("A Convex Float64.")
        case .int64(semantic: .commitTimestamp):
            notes.append("A commit timestamp in nanoseconds, resolved by the backend.")
        case .int64:
            notes.append("A Convex Int64.")
        case .bytes:
            notes.append("Convex bytes.")
        case .dynamic:
            notes.append("Explicitly dynamic: the contract provides no static type for this value.")
        default:
            break
        }
        if !notes.isEmpty {
            lines.append("")
            lines.append(notes.joined(separator: " "))
        }
        return lines
    }

    private mutating func emitTuple(
        _ elements: [Shape],
        at path: ContractPath,
        type: QualifiedName,
        documentation: [String]
    ) {
        // Element names also become locals in the generated decoder.
        scopes[type] = Scope(reserved: [
            "container", "count", "decodeConvex", "decoder", "encodeConvex", "encoder",
        ])
        var result: [TupleElement] = []
        for (index, element) in elements.enumerated() {
            let elementPath = path.member("elements").index(index)
            let name = overrides.take(elementPath) ?? "element\(index)"
            register(
                name,
                in: type,
                isType: false,
                label: "`\(elementPath)`",
                key: elementPath,
                origin: elementPath
            )
            let lowered = lowerShape(
                element,
                at: elementPath,
                parent: type,
                base: Identifier.upperFirst(name),
                naming: .derived(elementPath)
            )
            result.append(
                TupleElement(
                    name: name,
                    type: lowered.type,
                    documentation: ["Element \(index) of the tuple."]
                )
            )
        }
        var lines = documentation
        lines.append("")
        lines.append("Encoded as a JSON array of exactly \(elements.count) elements.")
        declarations.append(Declaration(name: type, documentation: lines, kind: .tuple(result)))
    }

    private mutating func emitUnion(
        _ variants: [(Shape, ContractPath)],
        at path: ContractPath,
        type: QualifiedName,
        documentation: [String]
    ) {
        scopes[type] = Scope(
            reserved: [
                "DiscriminantKey", "allCases", "convexKey", "decodeConvex", "encodeConvex",
                "rawValue",
            ]
        )
        guard let plan = analyze(variants, at: path) else {
            return
        }
        var cases: [UnionCase] = []
        var caseNames: [String] = []
        for (index, (shape, variantPath)) in variants.enumerated() {
            let defaultName = defaultCaseName(shape, tags: plan.tags[index])
            let name = resolveName(for: variantPath, derived: defaultName, what: "union variant")
            register(
                name,
                in: type,
                isType: false,
                label: "`\(variantPath)`",
                key: variantPath,
                origin: variantPath
            )
            caseNames.append(name)
            if case .literal(let value) = shape {
                cases.append(
                    UnionCase(
                        name: name,
                        payload: nil,
                        literal: value,
                        documentation: ["The literal \(Self.describe(value))."]
                    )
                )
            } else {
                let lowered = lowerShape(
                    shape,
                    at: variantPath,
                    parent: type,
                    base: Identifier.upperFirst(name),
                    naming: .derived(variantPath)
                )
                cases.append(
                    UnionCase(
                        name: name,
                        payload: lowered.type,
                        literal: nil,
                        documentation: ["The variant at `\(variantPath)`."]
                    )
                )
            }
        }
        var branches: [KindBranch] = []
        for group in plan.groups {
            let match: Match
            if group.indices.count == 1, let index = group.indices.first {
                if case .literal(let value) = variants[index].0 {
                    match = .values([
                        Branch(values: [value], caseName: caseNames[index], decodesPayload: false)
                    ])
                } else {
                    match = .single(caseName: caseNames[index])
                }
            } else if group.kind == .object, let field = plan.discriminant {
                match = .discriminant(
                    field: field,
                    branches: group.indices.map {
                        Branch(
                            values: plan.tags[$0] ?? [],
                            caseName: caseNames[$0],
                            decodesPayload: true
                        )
                    }
                )
            } else {
                match = .values(
                    group.indices.map { index in
                        if case .literal(let value) = variants[index].0 {
                            return Branch(
                                values: [value],
                                caseName: caseNames[index],
                                decodesPayload: false
                            )
                        }
                        var values: [LiteralValue] = []
                        if case .values(let set) = signature(of: variants[index].0)[group.kind] {
                            values = set.sorted(by: LiteralValue.precedes)
                        }
                        return Branch(
                            values: values,
                            caseName: caseNames[index],
                            decodesPayload: true
                        )
                    }
                )
            }
            branches.append(KindBranch(kind: group.kind, match: match))
        }
        var lines = documentation
        if let field = plan.discriminant {
            lines.append("")
            lines.append(
                "Object variants are selected by their required `\(field)` field; unknown values are rejected."
            )
        }
        declarations.append(
            Declaration(
                name: type,
                documentation: lines,
                kind: .union(Union(cases: cases, branches: branches))
            )
        )
    }

    /// Proves that at most one variant accepts any wire value, or reports why it cannot.
    private mutating func analyze(_ variants: [(Shape, ContractPath)], at path: ContractPath)
        -> UnionPlan?
    {
        var members: [WireKind: [(index: Int, constraint: Constraint)]] = [:]
        for (index, variant) in variants.enumerated() {
            for (kind, constraint) in signature(of: variant.0) {
                members[kind, default: []].append((index, constraint))
            }
        }
        var discriminant: String?
        var tags: [Int: [LiteralValue]] = [:]
        for kind in members.keys.sorted() {
            guard let group = members[kind], group.count > 1 else {
                continue
            }
            let paths = group.map { "`\(variants[$0.index].1)`" }.joined(separator: ", ")
            switch kind {
            case .boolean, .string, .float64, .int64:
                var seen: Set<LiteralValue> = []
                for member in group {
                    guard case .values(let values) = member.constraint,
                        seen.isDisjoint(with: values)
                    else {
                        report(
                            .overlappingUnion,
                            "Union variants \(paths) overlap on the \(kind.caseName) wire kind; only distinct literals of one wire kind can share a union.",
                            path
                        )
                        return nil
                    }
                    seen.formUnion(values)
                }
            case .object:
                var objects: [(index: Int, object: ObjectShape)] = []
                for member in group {
                    if case .object(let object) = member.constraint {
                        objects.append((member.index, object))
                    }
                }
                guard objects.count == group.count, let found = findDiscriminant(objects) else {
                    report(
                        .overlappingUnion,
                        "Union variants \(paths) overlap on the object wire kind. Give each object variant a required literal field with distinct values, such as `kind`, in the backend.",
                        path
                    )
                    return nil
                }
                discriminant = found.field
                tags = found.tags
            case .bytes, .array:
                report(
                    .overlappingUnion,
                    "Union variants \(paths) overlap on the \(kind.caseName) wire kind and cannot be told apart.",
                    path
                )
                return nil
            }
        }
        let groups = members.keys.sorted().map { kind in
            (kind: kind, indices: (members[kind] ?? []).map(\.index))
        }
        return UnionPlan(groups: groups, discriminant: discriminant, tags: tags)
    }

    private func findDiscriminant(
        _ objects: [(index: Int, object: ObjectShape)]
    ) -> (field: String, tags: [Int: [LiteralValue]])? {
        guard let first = objects.first else {
            return nil
        }
        let candidates = first.object.fields.filter { !$0.optional }.map(\.name).sorted()
        for candidate in candidates {
            var seen: Set<LiteralValue> = []
            var tags: [Int: [LiteralValue]] = [:]
            var valid = true
            for (index, object) in objects {
                guard
                    let field = object.fields.first(where: { $0.name == candidate && !$0.optional }
                    ),
                    let values = literalValues(field.type),
                    seen.isDisjoint(with: values)
                else {
                    valid = false
                    break
                }
                seen.formUnion(values)
                tags[index] = values.sorted(by: LiteralValue.precedes)
            }
            if valid {
                return (candidate, tags)
            }
        }
        return nil
    }

    private func literalValues(_ shape: Shape) -> Set<LiteralValue>? {
        switch contract.resolved(shape) {
        case .literal(let value):
            return [value]
        case .union(let variants):
            var values: Set<LiteralValue> = []
            for variant in variants {
                guard let nested = literalValues(variant) else {
                    return nil
                }
                values.formUnion(nested)
            }
            return values.isEmpty ? nil : values
        default:
            return nil
        }
    }

    /// The wire kinds a shape accepts and which values of each kind.
    private func signature(of shape: Shape) -> [WireKind: Constraint] {
        switch contract.resolved(shape) {
        case .string, .id:
            return [.string: .any]
        case .boolean:
            return [.boolean: .any]
        case .float64:
            return [.float64: .any]
        case .int64:
            return [.int64: .any]
        case .bytes:
            return [.bytes: .any]
        case .array, .tuple:
            return [.array: .any]
        case .record:
            return [.object: .any]
        case .object(let object):
            return [.object: .object(object)]
        case .literal(let value):
            return [value.wireKind: .values([value])]
        case .null, .ref:
            return [:]
        case .dynamic:
            return Dictionary(uniqueKeysWithValues: WireKind.allCases.map { ($0, Constraint.any) })
        case .union(let variants):
            var merged: [WireKind: Constraint] = [:]
            for variant in variants {
                for (kind, constraint) in signature(of: variant) {
                    if case .values(let existing) = merged[kind],
                        case .values(let added) = constraint
                    {
                        merged[kind] = .values(existing.union(added))
                    } else if merged[kind] == nil {
                        merged[kind] = constraint
                    } else {
                        merged[kind] = .any
                    }
                }
            }
            return merged
        }
    }

    private func defaultCaseName(_ shape: Shape, tags: [LiteralValue]?) -> String? {
        switch shape {
        case .literal(let value):
            return Self.literalCaseName(value)
        case .ref(let name):
            return namedTypes[name].map { Identifier.lowerFirst($0.name) }
        case .object:
            if let tags, tags.count == 1, case .string(let tag) = tags[0] {
                return Identifier.lowerCamel(tag)
            }
            return "object"
        case .string: return "string"
        case .id: return "id"
        case .boolean: return "boolean"
        case .float64: return "float64"
        case .int64: return "int64"
        case .bytes: return "bytes"
        case .array: return "array"
        case .tuple: return "tuple"
        case .record: return "record"
        case .null, .dynamic, .union: return nil
        }
    }

    private static func literalCaseName(_ value: LiteralValue) -> String? {
        switch value {
        case .string(let text):
            return Identifier.lowerCamel(text)
        case .boolean(let flag):
            return flag ? "true" : "false"
        case .float64(let number):
            let text =
                number == number.rounded() && abs(number) < 9_007_199_254_740_992
                ? String(Int64(number)) : number.description
            return "number" + numberSuffix(text)
        case .int64(let number):
            return "integer" + numberSuffix(String(number))
        }
    }

    private static func numberSuffix(_ text: String) -> String {
        var result = ""
        for character in text {
            switch character {
            case "-": result += "Minus"
            case ".": result += "_"
            case "+": break
            default: result.append(character)
            }
        }
        return result
    }

    static func describe(_ value: LiteralValue) -> String {
        switch value {
        case .string(let text): "`\"\(text.replacingBackticks())\"`"
        case .boolean(let flag): "`\(flag)`"
        case .float64(let number): "`\(number)`"
        case .int64(let number): "Int64 `\(number)`"
        }
    }

    // MARK: Unions

    private mutating func normalize(_ shape: Shape, at path: ContractPath) -> Normalized {
        guard case .union(let variants) = shape else {
            return .single(shape, path)
        }
        var flat: [(Shape, ContractPath)] = []
        flatten(variants, at: path, into: &flat)
        var hasNull = false
        var nonNull: [(Shape, ContractPath)] = []
        for variant in flat {
            if case .null = variant.0 {
                hasNull = true
            } else {
                nonNull.append(variant)
            }
        }
        guard let first = nonNull.first else {
            return .null
        }
        if nonNull.count == 1 {
            // Null is already part of a dynamic or nullable named variant.
            if !hasNull || isNullable(first.0) {
                return .single(first.0, first.1)
            }
            return .nullable(first.0, first.1)
        }
        if let nullable = nonNull.first(where: { isNullable($0.0) }) {
            let reason: String
            if case .dynamic = nullable.0 {
                reason = "an explicitly dynamic variant accepts every value"
            } else {
                reason = "a nullable named type cannot share a union with other variants"
            }
            report(
                .overlappingUnion,
                "Union variant `\(nullable.1)` overlaps the others: \(reason).",
                path
            )
            return .invalid
        }
        var literals: [(LiteralValue, ContractPath)] = []
        for (variant, variantPath) in nonNull {
            guard case .literal(let value) = variant else {
                return .union(nonNull, nullable: hasNull)
            }
            literals.append((value, variantPath))
        }
        return .literals(literals, nullable: hasNull)
    }

    private func flatten(
        _ variants: [Shape],
        at path: ContractPath,
        into flat: inout [(Shape, ContractPath)]
    ) {
        for (index, variant) in variants.enumerated() {
            let variantPath = path.member("variants").index(index)
            if case .union(let nested) = variant {
                flatten(nested, at: variantPath, into: &flat)
            } else if !flat.contains(where: { $0.0 == variant }) {
                flat.append((variant, variantPath))
            }
        }
    }

    private func isNullable(_ shape: Shape) -> Bool {
        switch contract.resolved(shape) {
        case .null, .dynamic: true
        case .union(let variants): variants.contains(where: isNullable)
        default: false
        }
    }

    private func referencesStorage() -> Bool {
        func visit(_ shape: Shape) -> Bool {
            switch shape {
            case .id(let table): table == "_storage"
            case .array(let element): visit(element)
            case .object(let object): object.fields.contains { visit($0.type) }
            case .record(let key, let value): visit(key) || visit(value)
            case .union(let variants): variants.contains(where: visit)
            case .tuple(let elements): elements.contains(where: visit)
            default: false
            }
        }
        return contract.types.values.contains(where: visit)
            || contract.tables.contains { visit($0.document) }
            || contract.functions.contains { visit(.object($0.arguments)) || visit($0.result) }
    }

    // MARK: Names

    private mutating func declareNested(
        in parent: QualifiedName,
        base: String,
        naming: Naming,
        origin: ContractPath
    ) -> QualifiedName {
        switch naming {
        case .position(let key):
            let name = overrides.take(key) ?? base
            register(
                name,
                in: parent,
                isType: true,
                label: "the type at `\(key)`",
                key: key,
                origin: origin
            )
            return parent.child(name)
        case .derived(let key):
            register(
                base,
                in: parent,
                isType: true,
                label: "the type of `\(key)`",
                key: key,
                origin: origin
            )
            return parent.child(base)
        }
    }

    /// Records a name in a scope, reporting reserved names and collisions.
    private mutating func register(
        _ name: String,
        in scope: QualifiedName,
        isType: Bool,
        label: String,
        key: ContractPath?,
        origin: ContractPath?
    ) {
        var current = scopes[scope] ?? Scope()
        var problem: String?
        // Generated code qualifies references through these names, so nothing may shadow them.
        if Self.reservedModules.contains(name) || name == root.name {
            problem = "is reserved in generated code"
        } else if isType, Identifier.keywords.contains(name) {
            problem = "is a Swift keyword"
        } else if !isType, Identifier.reservedMemberNames.contains(name) {
            problem = "cannot name a generated member"
        }
        if problem == nil, current.reserved.contains(name) {
            problem = "conflicts with a generated member"
        }
        var other: Member?
        if problem == nil, let existing = current.members[name] {
            problem = "collides with \(existing.label)"
            other = existing
        } else if problem == nil, isType, let existing = current.lowercasedTypes[name.lowercased()]
        {
            problem = "differs only in case from \(existing.label)"
            other = existing
        }
        if let problem {
            let keys = [key, other?.key].compactMap { $0.map { "`\($0)`" } }
            let fix =
                keys.isEmpty
                ? "rename the backend declaration"
                : "add a `names` override for \(keys.joined(separator: " or "))"
            diagnostics.append(
                ContractDiagnostic(
                    code: .nameCollision,
                    message:
                        "The Swift name `\(name)` for \(label) in `\(scope)` \(problem); \(fix).",
                    path: origin ?? key,
                    location: (origin ?? key).flatMap { contract.location(of: $0) },
                    source: source
                )
            )
            return
        }
        let member = Member(label: label, key: key)
        current.members[name] = member
        if isType {
            current.lowercasedTypes[name.lowercased()] = member
        }
        scopes[scope] = current
    }

    /// The override for a path, else the derived name, else a reported placeholder.
    private mutating func resolveName(for path: ContractPath, derived: String?, what: String)
        -> String
    {
        if let override = overrides.take(path) {
            return override
        }
        if let derived {
            return derived
        }
        return unnameable(path, what)
    }

    private mutating func unnameable(_ path: ContractPath, _ what: String) -> String {
        report(
            .unnameable,
            "Cannot derive a Swift identifier for this \(what); add a `names` override for `\(path)`.",
            path
        )
        return "<\(path)>"
    }

    private mutating func report(
        _ code: ContractDiagnostic.Code,
        _ message: String,
        _ path: ContractPath
    ) {
        diagnostics.append(
            ContractDiagnostic(
                code: code,
                message: message,
                path: path,
                location: contract.location(of: path),
                source: source
            )
        )
    }
}

/// Swift spelling overrides keyed by rendered contract paths.
struct NameOverrides {
    let entries: [String: String]
    private let locations: [String: TextLocation]
    private var used: Set<String> = []

    init(_ entries: [String: String], locations: [String: TextLocation] = [:]) {
        self.entries = entries
        self.locations = locations
    }

    /// Returns the override for a path and marks it used.
    mutating func take(_ path: ContractPath) -> String? {
        let key = path.description
        guard let value = entries[key] else {
            return nil
        }
        used.insert(key)
        return value
    }

    var unusedKeys: [String] {
        entries.keys.filter { !used.contains($0) }.sorted()
    }

    func location(of key: String) -> TextLocation? {
        locations[key]
    }
}

extension String {
    func replacingBackticks() -> String {
        replacing("`", with: "'")
    }
}
